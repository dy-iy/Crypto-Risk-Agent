export type LabelKey = keyof typeof LABELS.en;

export function t(language: LanguageMode, key: LabelKey) {
  return LABELS[language][key] ?? LABELS.en[key];
}

export function modeLabel(language: LanguageMode, mode: ProductViewMode) {
  if (mode === "learn") return t(language, "learnMode");
  if (mode === "auditor") return t(language, "auditorMode");
  if (mode === "raw") return t(language, "rawMode");
  return t(language, "reportMode");
}
